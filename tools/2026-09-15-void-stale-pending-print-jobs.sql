-- ---------------------------------------------------------------------------
-- §2 作廢
--
-- 🔴 預設只作廢「30 分鐘前」嘅積壓，保留最近 30 分鐘嘅單 ——
--    因為中繼機重啟後，**最近嘅單仍然係廚房／收銀需要嘅**（唔應該一齊殺）。
--    想改範圍就改下面 `v_cutoff`。
--
-- 為何 `attempts = 5`：
--   `0035` 嘅 claim 要求 `coalesce(attempts,0) < 5` ⇒ 設成 5 就**永久唔會被 claim**。
--   呢個係「跳過」嘅乾淨做法：唔使刪 row、保留審計痕跡、UI 亦睇得到。
-- ---------------------------------------------------------------------------
do $$
declare
  v_cutoff timestamptz := now() - interval '30 minutes';   -- ← 想改範圍就改呢行
  v_count  integer;
begin
  update public.pos_print_jobs
     set status     = 'failed',
         attempts   = 5,
         last_error = '作廢：中繼機離線期間積壓，為免重啟後一次過補印舊紙而作廢（2026-09-15 事故）',
         updated_at = now()
   where status = 'pending'
     and created_at < v_cutoff;

  get diagnostics v_count = row_count;
  raise notice '已作廢 % 張陳舊 pending 打印任務（cutoff = %）', v_count, v_cutoff;
end $$;


